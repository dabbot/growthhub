-- Company workspaces: anyone can add a company by its website and app store links,
-- and the builder generates every dashboard section for it.
-- All reads and writes go through server code with the service role.

CREATE TABLE public.companies (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  slug text NOT NULL UNIQUE,
  name text NOT NULL,
  -- Work-email domain of the creator; teammates on the same domain share the company.
  -- NULL for personal email addresses (private to the creator) and for the demo.
  team_domain text,
  website_url text,
  play_url text,
  appstore_url text,
  country text NOT NULL DEFAULT 'India',
  competitors_hint text,
  description_hint text,
  status text NOT NULL DEFAULT 'approved',          -- pending | approved | rejected | revoked
  build_status text NOT NULL DEFAULT 'queued',      -- queued | building | ready | paused | failed
  build_step text,
  build_error text,
  build_lock_until timestamptz,
  -- true = the hand-built demo screens (Acme); false = sections generated by the builder
  demo boolean NOT NULL DEFAULT false,
  sector text,
  profile jsonb NOT NULL DEFAULT '{}'::jsonb,
  section_map jsonb NOT NULL DEFAULT '[]'::jsonb,
  created_by uuid,
  created_email text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX companies_team_domain_idx ON public.companies (team_domain);
CREATE INDEX companies_created_by_idx ON public.companies (created_by);
CREATE TRIGGER companies_updated BEFORE UPDATE ON public.companies
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

CREATE TABLE public.company_members (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  company_id uuid NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
  user_id uuid NOT NULL,
  email text NOT NULL,
  role text NOT NULL DEFAULT 'member',             -- owner | member
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (company_id, user_id)
);
CREATE INDEX company_members_user_idx ON public.company_members (user_id);

CREATE TABLE public.company_sections (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  company_id uuid NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
  section_key text NOT NULL,
  status text NOT NULL DEFAULT 'pending',          -- pending | ready | failed
  content jsonb NOT NULL DEFAULT '{}'::jsonb,
  error text,
  generated_at timestamptz,
  UNIQUE (company_id, section_key)
);

-- Server-only tables: no browser access through the Data API.
REVOKE ALL ON public.companies, public.company_members, public.company_sections FROM anon, authenticated;
GRANT ALL ON public.companies, public.company_members, public.company_sections TO service_role;
ALTER TABLE public.companies ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.company_members ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.company_sections ENABLE ROW LEVEL SECURITY;
CREATE POLICY "service role manages companies" ON public.companies FOR ALL TO service_role USING (true) WITH CHECK (true);
CREATE POLICY "service role manages company members" ON public.company_members FOR ALL TO service_role USING (true) WITH CHECK (true);
CREATE POLICY "service role manages company sections" ON public.company_sections FOR ALL TO service_role USING (true) WITH CHECK (true);

